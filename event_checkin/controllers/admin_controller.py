def _format_vn_datetime(dt):
    # Event schedule fields (ngay_bat_dau, thoi_gian_mo_dang_ky, ...) are typed by the
    # admin into a plain datetime-local input and stored as-is -- they're already
    # Vietnam wall-clock time, never UTC, so no timezone conversion belongs here.
    # Anything generated by datetime.utcnow() (registration/check-in timestamps) must
    # go through format_utc_as_vn() instead -- see call sites below.
    return dt.strftime("%d/%m/%Y %H:%M") if dt else ""


def _parse_datetime(value, field_name):
    value = (value or "").strip()
    if not value:
        raise ValueError(f"Vui lòng nhập {field_name}.")
    try:
        return datetime.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"{field_name} không hợp lệ.") from exc


def _parse_capacity(raw_value):
    """None nếu để trống (không giới hạn); ném ValueError nếu nhập nhưng không
    phải số nguyên dương -- gọi trong try/except ở nơi dùng."""
    raw_value = (str(raw_value).strip() if raw_value is not None else "")
    if not raw_value:
        return None
    value = int(raw_value)
    if value < 1:
        raise ValueError("so_luong_toi_da phải >= 1")
    return value


