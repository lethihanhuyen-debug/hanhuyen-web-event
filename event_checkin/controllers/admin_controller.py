@admin_bp.post("/api/admin/events")
@admin_required
def create_event():
    payload = request.get_json(silent=True) or request.form
    ten_su_kien = (payload.get("ten_su_kien") or "").strip()
    if not ten_su_kien:
        return jsonify({"success": False, "message": "Vui lòng nhập tên sự kiện."}), 400

    try:
        ngay_bat_dau = _parse_datetime(payload.get("ngay_bat_dau"), "ngay bat dau")
        ngay_ket_thuc = _parse_datetime(payload.get("ngay_ket_thuc"), "ngay ket thuc")
        thoi_gian_mo_dang_ky = _parse_datetime(payload.get("thoi_gian_mo_dang_ky"), "thời gian mở đăng ký")
        thoi_gian_dong_dang_ky = _parse_datetime(payload.get("thoi_gian_dong_dang_ky"), "thời gian đóng đăng ký")
    except ValueError as error:
        return jsonify({"success": False, "message": str(error)}), 400

    if ngay_ket_thuc < ngay_bat_dau:
        return jsonify({"success": False, "message": "Ngày kết thúc phải sau ngày bắt đầu."}), 400
    if thoi_gian_dong_dang_ky < thoi_gian_mo_dang_ky:
        return jsonify({"success": False, "message": "Thời gian đóng đăng ký phải sau thời gian mở đăng ký."}), 400
    # Registration must open no later than the event itself starts -- otherwise
    # the event would already be running with nobody able to register yet.
    if thoi_gian_mo_dang_ky > ngay_bat_dau:
        return jsonify({"success": False, "message": "Thời gian mở đăng ký phải trước hoặc bằng lúc sự kiện bắt đầu."}), 400
    # Registration must close no later than the event itself starts -- no
    # walk-in/late registration once the event is already running.
    if thoi_gian_dong_dang_ky > ngay_bat_dau:
        return jsonify({"success": False, "message": "Thời gian đóng đăng ký phải trước hoặc bằng lúc sự kiện bắt đầu."}), 400

    now = now_vn_naive()
    if ngay_bat_dau < now:
        return jsonify({"success": False, "message": "Ngày bắt đầu không được ở trong quá khứ."}), 400
    if thoi_gian_mo_dang_ky < now:
        return jsonify({"success": False, "message": "Thời gian mở đăng ký không được ở trong quá khứ."}), 400
    if thoi_gian_dong_dang_ky < now:
        return jsonify({"success": False, "message": "Thời gian đóng đăng ký không được ở trong quá khứ."}), 400

    co_so = (payload.get("co_so") or "").strip() or None
    if co_so and co_so not in CO_SO_CHOICES:
        return jsonify({"success": False, "message": "Cơ sở không hợp lệ."}), 400

    try:
        so_luong_toi_da = _parse_capacity(payload.get("so_luong_toi_da"))
    except ValueError:
        return jsonify({"success": False, "message": "Số lượng tham gia phải là số nguyên dương."}), 400

    event = Event(
        ten_su_kien=ten_su_kien,
        hinh=(payload.get("hinh") or "").strip() or None,
        mo_ta=(payload.get("mo_ta") or "").strip() or None,
        dia_diem=(payload.get("dia_diem") or "").strip() or None,
        co_so=co_so,
        so_luong_toi_da=so_luong_toi_da,
        ngay_bat_dau=ngay_bat_dau,
        ngay_ket_thuc=ngay_ket_thuc,
        thang=ngay_bat_dau.month,
        nam=ngay_bat_dau.year,
        thoi_gian_mo_dang_ky=thoi_gian_mo_dang_ky,
        thoi_gian_dong_dang_ky=thoi_gian_dong_dang_ky,
        # Status is derived live from the schedule (Event.computed_status), never
        # picked by the admin -- a brand-new event always starts out "upcoming"
        # since ngay_bat_dau/thoi_gian_mo_dang_ky are guaranteed not in the past above.
        trang_thai="upcoming",
        certificate_enabled=True,
        created_by=session["admin_id"],
        created_at=datetime.utcnow(),
    )
    db.session.add(event)
    db.session.commit()
    return jsonify({"success": True, "message": "Đã tạo sự kiện mới.", "data": _event_payload(event)})


