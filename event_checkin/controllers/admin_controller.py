@admin_bp.delete("/api/admin/events/<int:event_id>")
@admin_required
def delete_event(event_id):
    # Deleting an event with existing registrations/check-ins/certificates is
    # allowed -- the admin UI warns and asks for confirmation before calling
    # this endpoint (see the js-delete-event handler), so by the time the
    # request arrives here the admin has already accepted that everything
    # below is removed along with the event.
    event = Event.query.get_or_404(event_id)

    certificate_paths = []
    for certificate in Certificate.query.filter_by(event_id=event_id).all():
        if certificate.file_url:
            static_prefix = url_for("static", filename="", _external=False)
            relative_path = certificate.file_url
            if relative_path.startswith(static_prefix):
                relative_path = relative_path[len(static_prefix):]
            certificate_paths.append(Path(current_app.static_folder) / relative_path)

    # Deleted in FK-dependency order: EmailLog references Certificate, both
    # reference Registration/CheckIn's (ma_cbsv, event_id) pair indirectly.
    from event_checkin.utils.lucky_draw import purge_event_data, remove_files
    lucky_files = purge_event_data(event_id)  # dữ liệu quay số + ảnh nền (có khoá ngoại sang events)
    EmailLog.query.filter_by(event_id=event_id).delete()
    Certificate.query.filter_by(event_id=event_id).delete()
    CheckinRecord.query.filter_by(event_id=event_id).delete()
    CheckIn.query.filter_by(event_id=event_id).delete()  # bảng cũ (dự phòng) vẫn có khoá ngoại sang events
    Registration.query.filter_by(event_id=event_id).delete()
    db.session.delete(event)
    db.session.commit()

    for path in certificate_paths:
        if path.exists():
            path.unlink(missing_ok=True)
    remove_files(lucky_files)

    return jsonify({"success": True, "message": "Đã xóa sự kiện."})


@admin_bp.delete("/api/admin/events/<int:event_id>/checkins/<ma_cbsv>")
@admin_required
def delete_event_checkin(event_id, ma_cbsv):
    event = Event.query.get_or_404(event_id)
    records = CheckinRecord.query.filter_by(event_id=event_id, patron_code=ma_cbsv).all()
    if not records:
        return jsonify({"success": False, "message": "Người dùng này chưa check-in sự kiện."}), 404

    certificate = Certificate.query.filter_by(event_id=event_id, ma_cbsv=ma_cbsv).first()
    certificate_path = None
    if certificate and certificate.file_url:
        static_prefix = url_for("static", filename="", _external=False)
        relative_path = certificate.file_url
        if relative_path.startswith(static_prefix):
            relative_path = relative_path[len(static_prefix):]
        certificate_path = Path(current_app.static_folder) / relative_path

        EmailLog.query.filter_by(
            event_id=event_id,
            ma_cbsv=ma_cbsv,
            certificate_code=certificate.certificate_code,
        ).update({
            "certificate_code": None,
            "attachment_path": None,
        })
        db.session.delete(certificate)

    # Xoá mọi lượt quét của người này. Xoá luôn dòng ở bảng cũ (nếu có) để script
    # chuyển dữ liệu chạy lại không đưa check-in đã xoá quay về.
    for item in records:
        db.session.delete(item)
    CheckIn.query.filter_by(event_id=event_id, ma_cbsv=ma_cbsv).delete()
    db.session.commit()

    if certificate_path and certificate_path.exists():
        certificate_path.unlink(missing_ok=True)

    return jsonify({"success": True, "message": f"Đã xóa check-in của mã {ma_cbsv}."})


@admin_bp.get("/admin/export/csv")
@admin_required
def export_csv():
    registrations = Registration.query.order_by(Registration.thoi_gian_dang_ky.asc()).all()
    today_checkin_map = _today_checkin_map()

    buffer = StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["STT", "Mã CB/SV", "Họ tên", "Đơn vị", "Email", "Giờ đăng ký", "Trạng thái check-in"])

    for position, registration in enumerate(registrations, start=1):
        user = registration.user
        checkin_item = today_checkin_map.get((registration.ma_cbsv, registration.event_id))
        writer.writerow([
            position,
            registration.ma_cbsv,
            user.ho_ten if user else "",
            user.ten_don_vi if user else "",
            user.email if user else "",
            format_utc_as_vn(registration.thoi_gian_dang_ky),
            "Đã check-in" if checkin_item else "Chưa check-in",
        ])

    response = Response(buffer.getvalue(), mimetype="text/csv; charset=utf-8")
    response.headers["Content-Disposition"] = "attachment; filename=checkin_report.csv"
    return response


